export const magicLinkSignInAction = async (formData: FormData) => {
  const email = formData.get('email')?.toString();
  const supabase = await createClient();
  // An absent `origin` header used to stringify to "null", producing the dead
  // link "null/auth/callback" in the outbound email.
  const origin = resolveRequestOrigin((await headers()).get('origin'));
  const redirectUrl = formData.get('redirect')?.toString();

  if (!email) {
    return encodedRedirect('error', '/sign-in', 'Email is required');
  }

  // Check if user exists in our database
  let existingProfile;
  try {
    existingProfile = await prisma.profile.findUnique({
      where: { email },
      select: { id: true, email: true, role: true },
    });
  } catch (dbError) {
    console.error('Database error during magic link profile lookup:', dbError);
    return encodedRedirect('error', '/sign-in', 'Database error. Please try again.');
  }

  if (!existingProfile) {
    return encodedRedirect(
      'error',
      '/sign-in',
      'No account found with this email. Please sign up first or use a different email.'
    );
  }

  // Determine redirect destination based on role and redirect parameter
  let redirectTo = '/menu'; // default for customers
  if (existingProfile.role === 'ADMIN') {
    redirectTo = '/admin';
  } else if (redirectUrl) {
    redirectTo = redirectUrl;
  }

  console.log('🪄 Sending magic link:', {
    email,
    origin,
    redirectTo,
    fullRedirectUrl: `${origin}/auth/callback?redirect_to=${redirectTo}`,
  });

  // Send magic link using OTP flow
  const { error } = await supabase.auth.signInWithOtp({
    email,
    options: {
      emailRedirectTo: `${origin}/auth/callback?redirect_to=${redirectTo}`,
      // Ensure this is treated as a magic link OTP, not PKCE
      shouldCreateUser: false, // Don't create new users through magic link
    },
  });

  if (error) {
    console.error('Magic link error:', error.message);

    // Provide more specific error messages
    if (error.message.includes('email not confirmed')) {
      return encodedRedirect('error', '/sign-in', 'Please verify your email address first.');
    } else if (error.message.includes('signup')) {
      return encodedRedirect('error', '/sign-in', 'Account not found. Please sign up first.');
    } else {
      return encodedRedirect('error', '/sign-in', 'Could not send magic link. Please try again.');
    }
  }

  console.log('✅ Magic link sent successfully to:', email);

  return encodedRedirect('success', '/sign-in', 'Check your email for a magic link to sign in!');
};

/**
 * Server Action to safely get authenticated user profile
 * This handles cookie operations properly within a Server Action context
 */
export async function getAuthenticatedUserProfile(): Promise<{
  isLoggedIn: boolean;
  userData: {
    id: string;
    name: string;
    email: string;
    phone: string;
  } | null;
  error: string | null;
}> {
  try {
    // Create Supabase client within Server Action context - this safely handles cookies
    const supabase = await createClient();

    // This call may trigger a token refresh and cookie setting, but it's safe in Server Actions
    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !user) {
      return {
        isLoggedIn: false,
        userData: null,
        error: authError?.message || 'User not authenticated',
      };
    }

    // Fetch user profile from database with robust connection management
    try {
      const profile = await withRetry(
        async () => {
          return await prisma.profile.findUnique({
            where: { id: user.id },
            select: {
              id: true,
              name: true,
              email: true,
              phone: true,
            },
          });
        },
        3,
        'getAuthenticatedUserProfile'
      );

      if (!profile) {
        return {
          isLoggedIn: false,
          userData: null,
          error: 'User profile not found',
        };
      }

      return {
        isLoggedIn: true,
        userData: {
          id: profile.id,
          name: profile.name || '',
          email: profile.email || user.email || '',
          phone: profile.phone || '',
        },
        error: null,
      };
    } catch (dbError) {
      console.error('Database error fetching user profile:', dbError);

      // Fallback to auth user data if database fails
      return {
        isLoggedIn: true,
        userData: {
          id: user.id,
          name: user.user_metadata?.full_name || user.user_metadata?.name || '',
          email: user.email || '',
          phone: user.phone || user.user_metadata?.phone || '',
        },
        error: null,
      };
    }
  } catch (error) {
    console.error('Error in getAuthenticatedUserProfile:', error);
    return {
      isLoggedIn: false,
      userData: null,
      error: 'Failed to fetch user profile',
    };
  }
}
